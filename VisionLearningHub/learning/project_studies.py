def study(key):
    compare,method,evidence,bug,broken,repair=CASES[key]
    return dict(steps=[dict(id=f'{key}.{i+1}',title=t,input=inp,implementation=impl,evidence=ev) for i,(t,inp,impl,ev) in enumerate(STEPS[key])],
      comparison=dict(title=compare,method=method,evidence=evidence),repair=dict(title=bug,broken=broken,task=repair))

def study_readme(key):
    value=study(key)
    text='\n\n## 工程专属小任务（自查，不计自动通关）\n'
    for step in value['steps']:text+='\n### '+step['id']+' '+step['title']+'\n\n输入：'+step['input']+'\n\n实现：'+step['implementation']+'\n\n验证证据：'+step['evidence']+'\n'
    c=value['comparison'];b=value['repair']
    return text+'\n## 方法对比：'+c['title']+'\n\n'+c['method']+'\n\n'+c['evidence']+'\n\n## 故障维修：'+b['title']+'\n\n错误示例：'+b['broken']+'\n\n'+b['task']+'\n\n用独立的study.py或自建模块运行实验，将参数、输出、中间图路径与结论写入工程复盘。最终仍需运行checkpoint.py和main.py验收。\n'
